`timescale 1 ns / 1 ps
// =============================================================================
// tb_soc_mnist - full-SoC test with REAL quantised weights and REAL MNIST digits
//
// What runs: cnn_soc_top (PicoRV32 + firmware + image BRAM + image_reader +
// sliding window + datapath + pool + dense + argmax), driven only through its
// UART pins, exactly like the board is driven by send_image.py:
//   'W' + 1722 weight bytes -> 'K';  per image 'S' + 784 pixels -> 'R', digit, 2 x u32 cycles.
//
// Reference: cnn_fpga/quantize.py writes the vectors below with a bit-exact
// integer model. Every image must match it EXACTLY:
//   - all 10 dense-layer logits (read from inside the DUT)
//   - the digit returned over UART
//   - the digit shown on HEX0
// At the end, the 'B' command runs the same network in software on the CPU,
// which gives the CPU-only cycle count for the speedup.
//
// Files (generated by quantize.py into tb/system/vectors/):
//   weights_uart.hex  1722 bytes   images.hex  N x 784 bytes
//   expected.hex      N digits     labels.hex  N labels    logits.hex  N x 10 int32
// The simulator must run in tb/system (firmware_k.hex are copied there by sw/Makefile).
// =============================================================================
module tb_soc_mnist;
    // ------------------------------------------------------------ settings
    parameter int    N_IMAGES   = 10;
    parameter string VEC_DIR    = "vectors/";
    localparam int   CLK_PERIOD = 20;           // 50 MHz
    localparam int   BAUD_RATE  = 2_500_000;    // fast UART for simulation only (20 clocks/bit)
    localparam int   BIT_PERIOD = 400;          // ns per UART bit at 2.5 MBaud
    localparam int   GAP_CLKS   = 100;          // idle clocks between bytes (CPU needs time to store each one)
    localparam int   N_WEIGHTS  = 1722;         // 9 + 2 + 1 + 1690 + 20
    localparam int   IMG_BYTES  = 784;

    // ------------------------------------------------------------ DUT
    logic       clk = 0;
    logic [3:0] key;
    logic       uart_rxd, uart_txd;
    logic [6:0] hex0, hex1, hex2, hex3, hex4, hex5, hex6, hex7;

    always #(CLK_PERIOD / 2) clk = ~clk;

    cnn_soc_top #(.BAUD_RATE(BAUD_RATE)) dut (
        .CLOCK_50(clk), .KEY(key), .UART_RXD(uart_rxd), .UART_TXD(uart_txd),
        .HEX0(hex0), .HEX1(hex1), .HEX2(hex2), .HEX3(hex3),
        .HEX4(hex4), .HEX5(hex5), .HEX6(hex6), .HEX7(hex7)
    );

    // ------------------------------------------------------------ test vectors
    logic [7:0]  weights_mem [0:N_WEIGHTS-1];
    logic [7:0]  images_mem  [0:N_IMAGES*IMG_BYTES-1];
    logic [7:0]  expected    [0:N_IMAGES-1];
    logic [7:0]  labels      [0:N_IMAGES-1];
    logic [31:0] exp_logits  [0:N_IMAGES*10-1];

    // ------------------------------------------------------------ scoreboard
    int errors       = 0;
    int cur_img      = 0;     // image currently in the accelerator (used by the logit monitor)
    int logit_checks = 0;
    int matches_label = 0;

    // ------------------------------------------------------------ UART helpers
    // Host -> FPGA: start bit, 8 data bits LSB first, stop bit, then an idle gap.
    task automatic send_byte(input logic [7:0] data);
        uart_rxd = 1'b0;                 #(BIT_PERIOD);
        for (int b = 0; b < 8; b++) begin
            uart_rxd = data[b];          #(BIT_PERIOD);
        end
        uart_rxd = 1'b1;                 #(BIT_PERIOD);
        repeat (GAP_CLKS) @(posedge clk);
    endtask

    // FPGA -> host: wait for the start bit, then sample each bit in its centre.
    task automatic recv_byte(output logic [7:0] data);
        @(negedge uart_txd);
        #(BIT_PERIOD * 3 / 2);
        for (int b = 0; b < 8; b++) begin
            data[b] = uart_txd;
            #(BIT_PERIOD);
        end
    endtask

    task automatic recv_u32(output logic [31:0] value);
        logic [7:0] b0, b1, b2, b3;
        recv_byte(b0); recv_byte(b1); recv_byte(b2); recv_byte(b3);
        value = {b3, b2, b1, b0};        // little-endian
    endtask

    function automatic logic [6:0] seg(input logic [3:0] v);
        case (v)
            4'h0: seg = 7'b1000000; 4'h1: seg = 7'b1111001; 4'h2: seg = 7'b0100100;
            4'h3: seg = 7'b0110000; 4'h4: seg = 7'b0011001; 4'h5: seg = 7'b0010010;
            4'h6: seg = 7'b0000010; 4'h7: seg = 7'b1111000; 4'h8: seg = 7'b0000000;
            4'h9: seg = 7'b0010000; default: seg = 7'b1111111;
        endcase
    endfunction

    // ------------------------------------------------------------ logit monitor
    // dense_layer sets valid_out and logits on the same edge, so on the next edge
    // both are visible together. This checks the arithmetic, not just the argmax.
    always @(posedge clk) begin
        if (dut.nn_pipeline.clf.dense_valid) begin
            for (int i = 0; i < 10; i++) begin
                logit_checks++;
                if (dut.nn_pipeline.clf.logits[i] !== exp_logits[cur_img*10 + i]) begin
                    errors++;
                    $display("[%0t] ERROR image %0d logit[%0d]: DUT %0d, expected %0d", $time, cur_img, i,
                             $signed(dut.nn_pipeline.clf.logits[i]), $signed(exp_logits[cur_img*10 + i]));
                end
            end
        end
    end

    // ------------------------------------------------------------ watchdog
    // While the testbench waits for a reply, 'deadline' holds the latest acceptable time.
    time deadline = 0;
    initial forever begin
        #100_000;
        if (deadline != 0 && $time > deadline) begin
            $display("FATAL: image %0d got no UART reply (gpio_out=%h, re_busy=%b, result_ready=%b)",
                     cur_img, dut.gpio_out, dut.re_busy, dut.result_ready);
            $finish;
        end
    end

    // ------------------------------------------------------------ one image
    task automatic run_image(input int k);
        logic [7:0]  token, digit;
        logic [31:0] acc_cycles, uart_cycles;

        cur_img = k;
        send_byte("S");
        for (int i = 0; i < IMG_BYTES; i++) send_byte(images_mem[k*IMG_BYTES + i]);

        deadline = $time + 2_000_000;                        // 2 ms is far more than one inference needs
        recv_byte(token);                                    // the watchdog below stops the run if nothing arrives
        recv_byte(digit);
        recv_u32(acc_cycles);
        recv_u32(uart_cycles);
        deadline = 0;
        #(BIT_PERIOD);                                       // let the firmware update HEX0

        if (token !== "R")            begin errors++; $display("ERROR image %0d: token %h, expected 'R'", k, token); end
        if (digit !== expected[k])    begin errors++; $display("ERROR image %0d: digit %0d, expected %0d", k, digit, expected[k]); end
        if (hex0  !== seg(digit[3:0])) begin errors++; $display("ERROR image %0d: HEX0 %b does not show %0d", k, hex0, digit); end
        if (digit == labels[k]) matches_label++;

        $display("image %0d: label %0d  python %0d  fpga %0d  | accelerator %0d cycles, image over UART %0d cycles %s",
                 k, labels[k], expected[k], digit, acc_cycles, uart_cycles,
                 (digit === expected[k]) ? "OK" : "MISMATCH");
    endtask

    // ------------------------------------------------------------ weights (once)
    task automatic load_weights();
        logic [7:0] ack;
        send_byte("W");
        for (int i = 0; i < N_WEIGHTS; i++) send_byte(weights_mem[i]);
        deadline = $time + 1_000_000;
        recv_byte(ack);
        deadline = 0;
        if (ack !== "K") begin errors++; $display("ERROR weight load: ack %h, expected 'K'", ack); end
        else $display("weights loaded (%0d bytes)", N_WEIGHTS);
    endtask

    // ------------------------------------------------------------ CPU-only baseline
    task automatic run_cpu_baseline(input int k);
        logic [7:0]  token, digit;
        logic [31:0] cpu_cycles;
        send_byte("B");
        deadline = $time + 100_000_000;                      // software inference takes a few ms
        recv_byte(token);
        recv_byte(digit);
        recv_u32(cpu_cycles);
        deadline = 0;
        if (token !== "B" || digit !== expected[k]) begin
            errors++;
            $display("ERROR CPU baseline: token %h digit %0d, expected 'B' and %0d", token, digit, expected[k]);
        end
        $display("CPU-only software inference of image %0d: digit %0d in %0d cycles", k, digit, cpu_cycles);
    endtask

    // ------------------------------------------------------------ main sequence
    initial begin
        $readmemh({VEC_DIR, "weights_uart.hex"}, weights_mem);
        $readmemh({VEC_DIR, "images.hex"},       images_mem);
        $readmemh({VEC_DIR, "expected.hex"},     expected);
        $readmemh({VEC_DIR, "labels.hex"},       labels);
        $readmemh({VEC_DIR, "logits.hex"},       exp_logits);
        // An array element that was never loaded is still X: check the LAST one of each file.
        if ($isunknown(weights_mem[N_WEIGHTS-1]) || $isunknown(images_mem[N_IMAGES*IMG_BYTES-1]) ||
            $isunknown(expected[N_IMAGES-1])     || $isunknown(exp_logits[N_IMAGES*10-1])) begin
            $display("FATAL: vector files missing or too short in '%s' (run cnn_fpga/quantize.py)", VEC_DIR);
            $finish;
        end

        uart_rxd = 1'b1;
        key      = 4'b1110;                  // KEY[0] low = reset
        repeat (20) @(posedge clk);
        key[0]   = 1'b1;
        // Boot: start.S clears ~2.5 KB of .bss before main() polls the UART (~0.3 ms).
        // The UART holds only one byte, so anything sent earlier is lost. Wait 1 ms.
        repeat (50_000) @(posedge clk);

        load_weights();
        for (int k = 0; k < N_IMAGES; k++) run_image(k);
        run_cpu_baseline(N_IMAGES - 1);

        $display("\n==============================================================");
        $display(" images: %0d   logit checks: %0d   matches MNIST label: %0d/%0d",
                 N_IMAGES, logit_checks, matches_label, N_IMAGES);
        if (logit_checks != N_IMAGES*10) begin
            errors++;
            $display(" ERROR: expected %0d logit checks", N_IMAGES*10);
        end
        if (errors == 0) $display(" PASS: FPGA matches the Python integer model bit for bit");
        else             $display(" FAIL: %0d errors", errors);
        $display("==============================================================");
        $finish;
    end
endmodule
